function getSportConfig(sportName) {
  const normalized = (sportName || '').trim();
  for (const [key, config] of Object.entries(SPORT_SPECIFICS)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      return config;
    }
  }
  return GENERAL_FALLBACK;
}

